static const uint32_t kBtClassCount = 3208;

inline const BtClassEntry *bt_class_find(uint32_t vt) {
    uint32_t lo = 0, hi = kBtClassCount;
    while (lo < hi) {
        uint32_t mid = (lo + hi) / 2;
        if (kBtClasses[mid].vt == vt) return &kBtClasses[mid];
        if (kBtClasses[mid].vt < vt) lo = mid + 1; else hi = mid;
    }
    return nullptr;
}

inline const char *bt_class_name(uint32_t vt) {
    const BtClassEntry *e = bt_class_find(vt);
    return e ? kBtBlob + e->name : nullptr;
}

inline const char *bt_class_cat(uint32_t vt) {
    const BtClassEntry *e = bt_class_find(vt);
    return e ? kBtBlob + e->cat : nullptr;
}

